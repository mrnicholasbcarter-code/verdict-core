"""Single source of truth for dependency security scan exceptions (BOD-342).

Reads config/security_exceptions.json so pip-audit (CI and scripts/certify_release.py)
and osv-scanner.toml (generated by scripts/generate_osv_exceptions.py) never carry two
drifting copies of the same exception list.

An exception only applies while all three hold: the vulnerability ID is listed, today
is on or before its expiry date, and the locked version of its package still matches
the version the exception was scoped to. Anything else (an unlisted ID, an expired
exception, or a package that moved to a different version) is reported, not ignored.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_EXCEPTIONS_PATH = ROOT / "config" / "security_exceptions.json"
DEFAULT_LOCK_PATH = ROOT / "uv.lock"


@dataclass(frozen=True)
class SecurityException:
    id: str
    package: str
    version: str
    reason: str
    expires: str  # YYYY-MM-DD
    removal_trigger: str

    def not_expired(self, today: date) -> bool:
        return today <= date.fromisoformat(self.expires)


def load_exceptions(path: Path = DEFAULT_EXCEPTIONS_PATH) -> list[SecurityException]:
    data = json.loads(path.read_text(encoding="utf-8"))
    return [SecurityException(**entry) for entry in data["exceptions"]]


def _tomllib() -> Any:
    try:
        import tomllib

        return tomllib
    except ModuleNotFoundError:
        import tomli

        return tomli


def locked_version(package: str, lock_path: Path = DEFAULT_LOCK_PATH) -> str | None:
    """Return the version pinned for `package` in uv.lock, or None if absent."""
    if not lock_path.exists():
        return None
    tomllib = _tomllib()
    data = tomllib.loads(lock_path.read_text(encoding="utf-8"))
    for pkg in data.get("package", []):
        if pkg.get("name") == package:
            version = pkg.get("version")
            return str(version) if version is not None else None
    return None


def active_ignore_ids(
    exceptions: list[SecurityException], *, today: date, lock_path: Path = DEFAULT_LOCK_PATH
) -> list[str]:
    """IDs to ignore right now: not expired, and the package is still at the pinned version."""
    ids: set[str] = set()
    for exc in exceptions:
        if not exc.not_expired(today):
            continue
        if locked_version(exc.package, lock_path) != exc.version:
            continue
        ids.add(exc.id)
    return sorted(ids)


def build_pip_audit_ignore_flags(
    *,
    today: date | None = None,
    exceptions_path: Path = DEFAULT_EXCEPTIONS_PATH,
    lock_path: Path = DEFAULT_LOCK_PATH,
) -> list[str]:
    """`--ignore-vuln <ID>` flags for every currently active exception."""
    from datetime import datetime, timezone

    resolved_today = today or datetime.now(timezone.utc).date()
    exceptions = load_exceptions(exceptions_path)
    ids = active_ignore_ids(exceptions, today=resolved_today, lock_path=lock_path)
    flags: list[str] = []
    for vuln_id in ids:
        flags += ["--ignore-vuln", vuln_id]
    return flags


def main() -> int:
    """CLI: print `--ignore-vuln <ID>` flags for pip-audit, space-separated."""
    flags = build_pip_audit_ignore_flags()
    print(" ".join(flags))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
